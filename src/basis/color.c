static intrin_wfn_t color_wfn_push(int ncfg, int nterm, const double *c, const char *const *s)
{
    intrin_wfn_t wfn = intrin_wfn_init(ncfg);
    for (int i = 0; i < nterm; i++) intrin_wfn_push(&wfn, c[i], s[i]);
    return wfn;
}

